writeFileSync(brewPath, brewSimple, 'utf8')

const scoop = {
  version,
  description: 'Teralexi CLI — local-first AI agent',
  homepage: 'https://www.teralexi.com/',
  license: 'Apache-2.0',
  architecture: {
    '64bit': {
      url: `https://github.com/Naughty-Otters/Teralexi/releases/download/v${version}/teralexi-windows-x64.zip`,
      hash: hashes['windows-x64'],
    },
  },
  bin: [['teralexi.cmd', 'teralexi']],
  depends: 'nodejs-lts',
  checkver: {
    github: 'https://github.com/Naughty-Otters/Teralexi',
  },
  autoupdate: {
    architecture: {
      '64bit': {
        url: 'https://github.com/Naughty-Otters/Teralexi/releases/download/v$version/teralexi-windows-x64.zip',
      },
    },
  },
}
writeFileSync(
  join(root, 'packaging', 'scoop', 'teralexi.json'),
  `${JSON.stringify(scoop, null, 2)}\n`,
  'utf8',
)

